using Cecla;
using Javadoc;

namespace AndroidBindgen;

public class Generator : IGenerator
{
    private const string ClassPointerName = "__ABG__Class";

    private readonly ClassManager _classManager;
    private readonly string? _customHeader;
    private readonly bool _ignoreDeprecated;
    private readonly JavadocManager? _javadocManager;
    private readonly Dictionary<string, int> _methodCount = new();
    private readonly Dictionary<string, int> _outputNameCount = new();
    private readonly Queue<(ClassFile classFile, IApiFilter filter)> _queuedClasses = new();
    private readonly Dictionary<ClassFile, IApiFilter> _queuedClassSet = new();

    private bool _isInGeneration;

    public Generator(ClassManager classManager, bool ignoreDeprecated, JavadocManager? javadocManager,
        string? customHeader = null)
    {
        _classManager = classManager;
        _ignoreDeprecated = ignoreDeprecated;
        _javadocManager = javadocManager;
        _customHeader = customHeader;
    }

    #region IGenerator Members

    public void Request(string className, IApiFilter filter)
    {
        if (!_classManager.TryGetClass(className, out var classFile))
        {
            Console.WriteLine($"Class not found: {className}\n{Environment.StackTrace}");
            return;
        }

        if (_queuedClassSet.TryGetValue(classFile, out var existingFilter))
        {
            if (existingFilter == IApiFilter.AllFilter) return;
            if (filter == IApiFilter.FacadeFilter) return;
            _queuedClassSet[classFile] = filter;
        }
        else
        {
            _queuedClassSet.Add(classFile, filter);
            if (_isInGeneration) _queuedClasses.Enqueue((classFile, filter));
        }
    }

    #endregion

    public void Generate(string outputDirectory)
    {
        if (_isInGeneration) throw new InvalidOperationException();

        // delete existing files
        Directory.CreateDirectory(outputDirectory);
        foreach (var file in Directory.EnumerateFiles(outputDirectory, "*.gen.cs")) File.Delete(file);

        _isInGeneration = true;
        try
        {
            foreach (var (classFile, filter) in _queuedClassSet)
                _queuedClasses.Enqueue((classFile, filter));

            while (_queuedClasses.TryDequeue(out var tuple))
                GenerateForClass(tuple.classFile, tuple.filter, outputDirectory);
        }
        finally
        {
            _isInGeneration = false;
        }
    }

    public void RequestFullMembers(string className)
    {
        if (!_classManager.TryGetClass(className, out var classFile))
        {
            Console.WriteLine($"Class not found: {className}\n{Environment.StackTrace}");
            return;
        }

        Request(className, IApiFilter.AllFilter);

        var superClassName = classFile.SuperClass?.Name;

        if (superClassName != null)
            Request(superClassName, IApiFilter.AllFilter);

        foreach (var @interface in classFile.Interfaces.Span)
            Request(@interface.Name ?? throw new InvalidOperationException(), IApiFilter.AllFilter);
    }

    private void GenerateForClass(ClassFile classFile, IApiFilter filter, string outputDirectory)
    {
        Console.WriteLine($"Generating: {classFile.ThisClass.Name}");
        StringBuilder sourceBuilder = new();

        var isPublic = classFile.AccessFlags.HasFlag(AccessFlags.Public);
        if (!isPublic && filter != IApiFilter.FacadeFilter)
        {
            Console.WriteLine($"Non-public class can only be generated as a facade: {classFile.ThisClass.Name}");
            return;
        }

        if (!string.IsNullOrEmpty(_customHeader)) sourceBuilder.AppendLine(_customHeader);
        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("#nullable enable");

        var classFullName = classFile.ThisClass.Name ?? throw new InvalidOperationException();
        var nameSpan = classFullName.AsSpan();
        var lastDot = nameSpan.LastIndexOf('/');

        var package = ReadOnlySpan<char>.Empty;
        if (lastDot >= 0)
        {
            package = nameSpan[..lastDot];
            nameSpan = nameSpan[(lastDot + 1)..];
        }

        sourceBuilder.AppendLine("#pragma warning disable CS0108");
        sourceBuilder.AppendLine("#pragma warning disable CS0162");
        sourceBuilder.AppendLine("#pragma warning disable CS0114");
        sourceBuilder.AppendLine("using global::System.Linq;");

        if (package.Length > 0)
        {
            sourceBuilder.AppendLine($"namespace {package.ToString().Replace('/', '.').ToSafeIdentifier()}");
            sourceBuilder.AppendLine("{");
        }

        var superClassName = classFile.SuperClass?.Name;

        Class? javadocClass = null;
        if (!_javadocManager?.TryGetClass(classFullName, out javadocClass) ?? false)
            Console.WriteLine(
                $"Javadoc not found for: {classFullName}. This may cause incomplete parameter names and documentation comments.");

        var cursor = 0;
        var depth = 0;
        ReadOnlySpan<char> lastName;
        do
        {
            ReadOnlySpan<char> currentName;
            var rest = nameSpan[cursor..];
            var dollar = rest.IndexOf('$');
            bool isPartialPlaceholder;
            if (dollar >= 0)
            {
                currentName = rest[..dollar];
                cursor += dollar;
                Request($"{package.ToString()}/{nameSpan[..cursor].ToString()}", IApiFilter.FacadeFilter);
                cursor++;
                isPartialPlaceholder = true;
            }
            else
            {
                currentName = rest;
                cursor = nameSpan.Length;
                isPartialPlaceholder = false;
            }

            var first = currentName[0];
            if (first is >= '0' and <= '9')
                currentName = $"_{currentName.ToString()}";

            if (!isPartialPlaceholder)
            {
                var javadoc = javadocClass?.Javadoc;
                if (javadoc != null && !string.IsNullOrEmpty(javadoc.Data))
                {
                    sourceBuilder.AppendLine("/// <summary>");
                    AppendJavadoc(sourceBuilder, javadoc);
                    sourceBuilder.AppendLine("/// </summary>");
                }

                if (!isPublic)
                    // Java allows inheritance from non-public classes, so we need to generate class definitions for non-public super classes.
                    sourceBuilder.AppendLine(
                        "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");

                sourceBuilder.Append("public ");
            }

            sourceBuilder.Append(
                $"partial interface @{currentName.ToString()}");

            if (!isPartialPlaceholder)
            {
                sourceBuilder.Append(" : ");

                // base class
                if (superClassName != null)
                {
                    Request(superClassName, IApiFilter.FacadeFilter);
                    sourceBuilder.Append(
                        $"global::{superClassName.Replace("$", ".").Replace("/", ".").ToSafeIdentifier()}");
                }
                else
                {
                    sourceBuilder.Append(
                        "global::AndroidBindgen.IAndroidJavaObject");
                }

                foreach (var @interface in classFile.Interfaces.Span)
                {
                    Request(@interface.Name ?? throw new InvalidOperationException(), IApiFilter.FacadeFilter);
                    sourceBuilder.Append(", global::");
                    sourceBuilder.Append(@interface.Name.Replace('$', '.').Replace('/', '.').ToSafeIdentifier());
                }

                sourceBuilder.AppendLine();
            }

            sourceBuilder.AppendLine("{");
            depth++;

            lastName = currentName;
        } while (cursor < nameSpan.Length);

        if (isPublic)
            GenerateMembers(sourceBuilder, classFile, classFullName, filter, lastName, javadocClass, superClassName);

        for (var i = 0; i < depth; i++)
            sourceBuilder.AppendLine("}");

        if (package.Length > 0)
            sourceBuilder.AppendLine("}");

        if (isPublic)
            GenerateBingingExtensions(sourceBuilder, package, classFile, filter, lastName, classFullName,
                ClassPointerName, javadocClass);

        var name = classFullName.Replace('/', '_').Replace('$', '_');

        var count = _outputNameCount.GetValueOrDefault(name, 0);
        _outputNameCount[name] = count + 1;

        File.WriteAllText(Path.Combine(outputDirectory, $"{name}_{count}.gen.cs"),
            sourceBuilder.ToString());
    }

    private void GenerateMembers(StringBuilder sourceBuilder, ClassFile classFile, string classFullName,
        IApiFilter filter, ReadOnlySpan<char> lastName, Class? javadocClass, string? superClassName)
    {
        var anonymousName = "__ABG__Anonymous";

        sourceBuilder.AppendLine($"    private static nint {ClassPointerName}_backingField;");
        sourceBuilder.AppendLine(
            $$"""
                  internal static nint {{ClassPointerName}}
                  {
                      get
                      {
                          var existing = {{ClassPointerName}}_backingField; 
                          if (existing != 0) return existing;
                      
                          var ptr = global::UnityEngine.AndroidJNI.NewGlobalRef(global::UnityEngine.AndroidJNI.FindClass(@"{{classFullName}}"));
                          existing = global::System.Threading.Interlocked.CompareExchange(ref {{ClassPointerName}}_backingField, ptr, (nint)0);
                          if (existing != (nint)0)
                          {
                              global::UnityEngine.AndroidJNI.DeleteGlobalRef(ptr);
                              return existing;
                          }
                          return ptr;
                      }
                  }
              """);

        foreach (var method in classFile.Methods.Span)
        {
            if (!filter.ShouldInclude(method)) continue;
            var isStatic = method.AccessFlags.HasFlag(AccessFlags.Static);
            var isConstructor = method.Name == "<init>";
            if (!isStatic && !isConstructor) continue;

            AppendMethod(
                sourceBuilder,
                method,
                lastName,
                classFullName,
                ClassPointerName,
                _methodCount,
                javadocClass);
        }

        foreach (var field in classFile.Fields.Span)
        {
            if (!filter.ShouldInclude(field)) continue;
            var isStatic = field.AccessFlags.HasFlag(AccessFlags.Static);
            if (!isStatic) continue;
            AppendField(
                sourceBuilder,
                field,
                classFullName,
                ClassPointerName,
                _methodCount);
        }

        var lastNameStr = lastName.ToString();

        sourceBuilder.AppendLine($$"""
                                       public static @{{lastNameStr}}? UnsafeFromRawObjectAndDeleteLocalRef(nint rawObject)
                                       {
                                           if (rawObject == (nint)0) return null;
                                           try
                                           {
                                               return new @{{anonymousName}}(rawObject);
                                           }
                                           finally
                                           {
                                               global::UnityEngine.AndroidJNI.DeleteLocalRef(rawObject);
                                           }
                                       }

                                       public static @{{lastNameStr}}? UnsafeFromRawObject(nint rawObject)
                                       {
                                           if (rawObject == (nint)0) return null;
                                           return new @{{anonymousName}}(rawObject);
                                       }

                                       public static @{{lastNameStr}}? FromRawObject(nint rawObject)
                                       {
                                           if (rawObject == (nint)0) return null;
                                           return !global::UnityEngine.AndroidJNI.IsAssignableFrom(global::UnityEngine.AndroidJNI.GetObjectClass(rawObject), {{ClassPointerName}}) ? null : new @{{anonymousName}}(rawObject);
                                       }

                                       public static @{{lastNameStr}}? FromRawObject(global::AndroidBindgen.IAndroidJavaObject source) => source != null ? FromRawObject(source.GetRawObject()) : null;
                                   """);

        sourceBuilder.Append(
            $$"""
              internal class {{anonymousName}} :  
              """);

        // base class
        if (superClassName != null)
        {
            Request(superClassName, IApiFilter.FacadeFilter);
            sourceBuilder.Append(
                $"global::{superClassName.Replace("$", ".").Replace("/", ".").ToSafeIdentifier()}.{anonymousName}, ");
        }
        else
        {
            sourceBuilder.Append(
                "global::UnityEngine.AndroidJavaObject, ");
        }

        sourceBuilder.AppendLine($"@{lastNameStr}");

        sourceBuilder.AppendLine(
            $$"""
              {
                  internal @{{anonymousName}}(nint rawObject) : base(rawObject) { }
              """);

        sourceBuilder.AppendLine(
            """}""");

        // proxy
        if (filter.ShouldIncludeProxy() && classFile.AccessFlags.HasFlag(AccessFlags.Interface))
        {
            sourceBuilder.AppendLine(
                $$"""
                  public abstract class ProxyBase : global::AndroidBindgen.ProxyBase, @{{lastNameStr}}
                  {
                  """);

            Dictionary<string /* method name */, Dictionary<int /* parameter count*/
                , Dictionary<string /* signature descriptor */
                    , (string name, ParameterInfo[] parameters, IParameterType returnType)>>> methods = new();

            List<ParameterInfo> tempParameters = new();

            HashSet<ClassFile> interfaces = new();

            void AddInterface(ClassFile @interface)
            {
                if (interfaces.Add(@interface))
                    foreach (var next in @interface.Interfaces.Span)
                    {
                        var name = next.Name ?? throw new InvalidOperationException();
                        if (!_classManager.TryGetClass(name, out var nextClass))
                            throw new InvalidOperationException($"Failed to load class: {name}");
                        AddInterface(nextClass);
                    }
            }

            AddInterface(classFile);
            foreach (var @interface in interfaces)
            foreach (var method in @interface.Methods.Span)
            {
                if (method.AccessFlags.HasFlag(AccessFlags.Static)) continue;
                if (!method.AccessFlags.HasFlag(AccessFlags.Public)) continue;
                if (method.AccessFlags.HasFlag(AccessFlags.Synthetic) &&
                    method.AccessFlags.HasFlag(AccessFlags.Bridge)) continue;

                var hasDefault = !method.AccessFlags.HasFlag(AccessFlags.Abstract);

                // find javadoc
                var javadocMethod = javadocClass?.Methods?.FirstOrDefault(m => m.JniSignature == method.Descriptor);

                if (!TryParseMethodDescriptor(method, tempParameters, out var returnType, this,
                        out var signatureDescriptor, javadocMethod)) continue;

                if (!methods.TryGetValue(method.Name, out var withName))
                    methods[method.Name] = withName =
                        new Dictionary<int, Dictionary<string, (string name, ParameterInfo[] parameters, IParameterType
                            returnType)>>();

                if (!withName.TryGetValue(tempParameters.Count, out var withParameterCount))
                    withName[tempParameters.Count] = withParameterCount =
                        new Dictionary<string, (string name, ParameterInfo[] parameters, IParameterType returnType)>();

                if (!withParameterCount.TryAdd(signatureDescriptor,
                        (method.Name, tempParameters.ToArray(), returnType))) continue;

                sourceBuilder.Append("    public ");
                sourceBuilder.Append(hasDefault ? "virtual " : "abstract ");

                sourceBuilder.Append(
/* lang=c# */
                    $"{returnType.GetCSharpExpression(true)} {method.Name}({string.Join(", ", tempParameters.Select(p => $"{p.Type.GetCSharpExpression(true)} {p.Name}"))})");

                sourceBuilder.AppendLine(hasDefault
                    /* lang=c# */
                    ? $$"""
                            {
                                throw new global::AndroidBindgen.InvocationErrorException("No such proxy method: {{method.Name}}({{string.Join(", ", tempParameters.Select(p => $"{p.Type.GetCSharpExpression(true)} {p.Name}"))}})");
                            }
                        """
                    : ";");
            }

            sourceBuilder.AppendLine(
/* lang=c#  */$$"""
                    private static global::UnityEngine.AndroidJavaClass? __ABG__Class_backingField;
                    private static global::UnityEngine.AndroidJavaClass __ABG__Class
                    {
                        get
                        {
                            var existing = __ABG__Class_backingField;
                            if(existing != null) return existing;
                            var newClass = new global::UnityEngine.AndroidJavaClass("{{classFullName}}");
                            if (global::System.Threading.Interlocked.CompareExchange(ref __ABG__Class_backingField, newClass, null) != null)
                            {
                                newClass.Dispose();
                                return __ABG__Class_backingField;
                            }
                            return newClass;
                        }
                    }
                    protected ProxyBase() : base(__ABG__Class)
                    {
                    }
                    
                    protected override bool InvokeCore(string methodName, global::System.ReadOnlySpan<nint> args, global::System.ReadOnlySpan<nint> argClasses, out global::System.IntPtr result)
                    {
                        var arrayLen = args.Length;
                        switch (methodName)
                        {
                """);

            foreach (var (methodName, withName) in methods)
            {
                sourceBuilder.AppendLine(
/* lang=c#  */$$"""
                            case @"{{methodName}}":
                            {
                                switch (arrayLen)
                                {
                """);
                foreach (var (parameterCount, withParameterCount) in withName)
                {
                    sourceBuilder.AppendLine(
/* lang=c#  */$$"""
                                    case {{parameterCount}}:
                                    {
                """);

                    // extract parameters
                    for (var i = 0; i < parameterCount; i++)
                        sourceBuilder.AppendLine(
                            /* lang=c#  */
                            $$"""
                                                      var class{{i}} = argClasses[{{i}}] == 0 ? null : GetBoxedTypeIdentifier(argClasses[{{i}}]);
                              """);

                    // matchers
                    var isFirst = true;
                    foreach (var (_, parameters, returnType) in withParameterCount.Values)
                    {
                        sourceBuilder.Append("                        ");
                        if (!isFirst)
                            sourceBuilder.Append("else ");

                        isFirst = false;
                        sourceBuilder.AppendLine(parameters.Length == 0
                            ? "if (true)"
                            : $"if ({string.Join(" && ", parameters.Select((parameter, i) => parameter.Type.GetProxyParameterMatcher($"class{i}", $"argClasses[{i}]", true)))})");

                        var context = new MarshalingContext("                            ",
                            "                                ");
                        sourceBuilder.AppendLine(
/* lang=c#  */"""                        {""");
                        var methodEx =
                            $"{methodName}({string.Join(", ", parameters.Select((parameter, i) => parameter.Type.GetProxyUnboxer(context, $"args[{i}]")))})";

                        sourceBuilder.Append(context.PreCall);

                        sourceBuilder.AppendLine(
/* lang=c#  */"""
                                          try
                                          {
              """);
                        sourceBuilder.AppendLine(returnType.IsVoid
                            /* lang=c#  */
                            ? $$"""
                                                                {{methodEx}};
                                                                result = global::System.IntPtr.Zero; return true;
                                """
                            /* lang=c#  */
                            : $$"""
                                                                result = {{returnType.GetProxyBoxer(methodEx)}}; return true;
                                """);

                        sourceBuilder.AppendLine(
/* lang=c#  */"""
                                          }
                                          finally
                                          {
              """);

                        sourceBuilder.Append(context.PostCall);

                        sourceBuilder.AppendLine(
/* lang=c#  */"""                            }""");

                        sourceBuilder.AppendLine(
/* lang=c#  */"""                        }""");
                    }

                    sourceBuilder.AppendLine(
/* lang=c#  */"""
                                      break;
                                  }
              """);
                }

                sourceBuilder.AppendLine(
/* lang=c#  */"""
                              }
                              break;
                          }
              """);
            }

            sourceBuilder.AppendLine(
/* lang=c#  */"""
                      }
                      result = default;
                      return false;
                  }
              """);

            sourceBuilder.AppendLine("}");
        }
    }

    private void GenerateBingingExtensions(StringBuilder sourceBuilder, ReadOnlySpan<char> package, ClassFile classFile,
        IApiFilter filter, ReadOnlySpan<char> lastName, string classFullName, string classPointerName,
        Class? javadocClass)
    {
        sourceBuilder.AppendLine(
/* lang=c#  */$$"""
                namespace {{package.ToString().Replace("/", ".")}}
                {
                public static partial class BindingExtensions
                {
                """);

        foreach (var method in classFile.Methods.Span)
        {
            if (!filter.ShouldInclude(method)) continue;
            var isStatic = method.AccessFlags.HasFlag(AccessFlags.Static);
            var isConstructor = method.Name == "<init>";
            if (isStatic || isConstructor) continue;
            AppendMethod(
                sourceBuilder,
                method,
                lastName,
                classFullName,
                classPointerName,
                _methodCount,
                javadocClass);
        }

        foreach (var field in classFile.Fields.Span)
        {
            if (!filter.ShouldInclude(field)) continue;
            var isStatic = field.AccessFlags.HasFlag(AccessFlags.Static);
            if (isStatic) continue;
            AppendField(
                sourceBuilder,
                field,
                classFullName,
                classPointerName,
                _methodCount);
        }

        sourceBuilder.AppendLine(
            """
            }
            }
            """);
    }

    private void AppendField(
        StringBuilder sourceBuilder,
        FieldInfo field,
        ReadOnlySpan<char> typeFullName,
        ReadOnlySpan<char> classPointerName,
        Dictionary<string, int> methodCount)
    {
        if (!field.AccessFlags.HasFlag(AccessFlags.Public)) return;
        if (_ignoreDeprecated && field.Attributes.Span.Any(attr => attr is AttributeDeprecated)) return;

        var descriptor = field.Descriptor;

        var name = field.Name;

        if (field.AccessFlags.HasFlag(AccessFlags.Synthetic)) return;

        IParameterType type;
        {
            var cursor = 0;
            type = Utils.ParseDescriptor(descriptor, ref cursor);
        }
        type.RequestDependencyForType(this);

        var classPointerNameStr = classPointerName.ToString();

        var methodKey = $"{classPointerNameStr}_{field.Name}";
        var count = methodCount.GetValueOrDefault(methodKey, 0);
        methodCount[methodKey] = count + 1;

        var methodPointerName = $"p_{classPointerNameStr}_{field.Name}_{count}";

        sourceBuilder.AppendLine($"    private static nint {methodPointerName};");

        classPointerNameStr =
            $"{typeFullName.ToString().ToGlobalTypeName()}.{classPointerNameStr}";

        var isStatic = field.AccessFlags.HasFlag(AccessFlags.Static);

        var fieldPointerUpdater =
            $"if ({methodPointerName} == (nint)0) {methodPointerName} = global::UnityEngine.AndroidJNI.Get{(isStatic ? "Static" : "")}FieldID({classPointerNameStr}, @\"{name}\", @\"{field.Descriptor}\");";

        // get
        {
            sourceBuilder.Append("    public static ");

            sourceBuilder.Append(type.GetCSharpExpression(true));
            sourceBuilder.Append(" get_");
            sourceBuilder.Append(field.Name);

            sourceBuilder.Append("(");
            if (!isStatic)
                sourceBuilder.Append(
                    $"this {typeFullName.ToString().ToGlobalTypeName()} @this");

            sourceBuilder.AppendLine(")");

            sourceBuilder.AppendLine($$"""
                                           {
                                               {{fieldPointerUpdater}}
                                               return {{type.ToCSharpValue(
                                                   $"global::UnityEngine.AndroidJNI.{type.GetFieldMethodName(isStatic)}({(isStatic ? classPointerNameStr : "@this.GetRawObject()")}, {methodPointerName})")}};
                                           }
                                       """);
        }

        var isFinal = field.AccessFlags.HasFlag(AccessFlags.Final);

        // set
        if (!isFinal)
        {
            sourceBuilder.Append("    public static void set_");
            sourceBuilder.Append(field.Name);

            sourceBuilder.Append("(");
            if (!isStatic)
            {
                sourceBuilder.Append(
                    $"this {typeFullName.ToString().ToGlobalTypeName()} @this");
                sourceBuilder.Append(", ");
            }

            sourceBuilder.Append(
                $"{type.GetCSharpExpression(true)} value");

            sourceBuilder.AppendLine(")");

            sourceBuilder.AppendLine($$"""
                                           {
                                               {{fieldPointerUpdater}}
                                               global::UnityEngine.AndroidJNI.{{type.SetFieldMethodName(isStatic)}}({{(isStatic ? classPointerNameStr : "@this.GetRawObject()")}}, {{methodPointerName}}, {{type.FromCSharpValue("value")}});
                                           }
                                       """);
        }
    }

    private static bool TryParseMethodDescriptor(MethodInfo methodInfo, List<ParameterInfo> parameters,
        [NotNullWhen(true)] out IParameterType? returnType, IGenerator generator, Method? javadocMethod)
    {
        return TryParseMethodDescriptor(methodInfo, parameters, out returnType, generator, out _, javadocMethod);
    }

    private static bool TryParseMethodDescriptor(
        MethodInfo methodInfo,
        List<ParameterInfo> parameters,
        [NotNullWhen(true)] out IParameterType? returnType,
        IGenerator generator,
        [NotNullWhen(true)] out string? signatureDescriptor,
        Method? javadocMethod)
    {
        var javadocParams = javadocMethod?.Parameters;
        var descriptor = methodInfo.Descriptor;
        var isStatic = methodInfo.AccessFlags.HasFlag(AccessFlags.Static);
        // parse descriptor
        if (descriptor.Length < 1 || descriptor[0] != '(')
        {
            returnType = null;
            signatureDescriptor = null;
            return false;
        }

        LocalVariableTableEntry[]? table = null;

        foreach (var methodAttr in methodInfo.Attributes.Span)
            if (methodAttr is AttributeCode code)
            {
                foreach (var codeAttr in code.Attributes.Span)
                    if (codeAttr is AttributeLocalVariableTable variableTable)
                    {
                        table = variableTable.LocalVariableTable.Span.ToArray().OrderBy(entry => entry.Index).ToArray();
                        break;
                    }

                break;
            }

        ReadOnlyMemory<ReadOnlyMemory<Annotation>>? parameterAnnotations = null;
        foreach (var methodAttr in methodInfo.Attributes.Span)
            if (methodAttr is AttributeRuntimeInvisibleParameterAnnotations annotations)
            {
                parameterAnnotations = annotations.Annotations;
                break;
            }

        parameters.Clear();
        int cursor;
        for (cursor = 1; cursor < descriptor.Length;)
        {
            var next = descriptor[cursor++];
            if (next == ')') break;

            cursor--;
            var type = Utils.ParseDescriptor(descriptor, ref cursor);

            var localVariableIndex = isStatic ? parameters.Count : parameters.Count + 1;
            string name;
            if (localVariableIndex < table?.Length)
                name = $"@{Utils.ToCSharpIdentifierCompatible(table[localVariableIndex].Name)}";
            else if (javadocParams != null && parameters.Count < javadocParams.Length)
                name = $"@{Utils.ToCSharpIdentifierCompatible(javadocParams[parameters.Count].Name!)}";
            else
                name = $"arg_{parameters.Count}";

            var isNullable = true;
            if (parameters.Count < parameterAnnotations?.Length)
            {
                var annotations = parameterAnnotations.Value.Span[parameters.Count];
                isNullable = annotations.Span.Any(annot => annot.Type == "Landroid/annotation/NonNull;");
            }

            parameters.Add(new ParameterInfo(type, name, isNullable));
            type.RequestDependencyForType(generator);
        }

        signatureDescriptor = descriptor[1..(cursor - 1)];

        returnType = Utils.ParseDescriptor(descriptor, ref cursor);
        returnType.RequestDependencyForType(generator);
        return true;
    }

    private void AppendMethod(
        StringBuilder sourceBuilder,
        MethodInfo method,
        ReadOnlySpan<char> typeName,
        ReadOnlySpan<char> typeFullName,
        ReadOnlySpan<char> classPointerName,
        Dictionary<string, int> methodCount,
        Class? javadocClass)
    {
        List<ParameterInfo> tempArguments = new();
        var isDeprecated = method.Attributes.Span.Any(attr => attr is AttributeDeprecated);
        if (!method.AccessFlags.HasFlag(AccessFlags.Public)) return;
        if (_ignoreDeprecated && isDeprecated) return;

        var descriptor = method.Descriptor;

        var name = method.Name;

        if (method.AccessFlags.HasFlag(AccessFlags.Synthetic)) return;

        var safeName = name;

        var isConstructor = name == "<init>";
        if (isConstructor) safeName = "__init__";

        // find javadoc
        var javadocMethod = javadocClass?.Methods?.FirstOrDefault(m => m.JniSignature == method.Descriptor);
        var javadoc = javadocMethod?.Javadoc;

        if (javadocMethod == null)
        {
            // NOTE: javadoc method is not generated for methods without parameters
            // Console.WriteLine($"javadoc method not found for {method.Name} in {typeFullName}, desc: {method.descriptor}");
        }

        if (!TryParseMethodDescriptor(method, tempArguments, out var returnType, this, javadocMethod)) return;

        var classPointerNameStr = classPointerName.ToString();
        var methodKey = $"{classPointerNameStr}_{safeName}";
        var count = methodCount.GetValueOrDefault(methodKey, 0);
        methodCount[methodKey] = count + 1;

        var methodPointerName = $"p_{classPointerNameStr}_{safeName}_{count}";

        classPointerNameStr =
            $"{typeFullName.ToString().ToGlobalTypeName()}.{classPointerNameStr}";

        sourceBuilder.AppendLine(
/* source=c#*/$$"""

                    private static nint {{methodPointerName}};

                    /// <summary>
                    ///     {{safeName}}
                """);

        AppendJavadoc(sourceBuilder, javadoc);

        sourceBuilder.AppendLine(
/* source=c#*/"""    /// </summary>""");
        foreach (var (_, paramName, _) in tempArguments)
            sourceBuilder.AppendLine(
                /* source=c#*/
                $$"""
                      /// <param name="{{paramName}}">value of {{paramName}}</param>
                  """);

        if (!returnType.IsVoid)
            sourceBuilder.AppendLine(
                /* source=c#*/
                $$"""
                      /// <returns>value of {{returnType.GetCSharpExpression(false)}}</returns>
                  """);

        sourceBuilder.Append("    ");


        sourceBuilder.Append("public static ");

        sourceBuilder.Append(isConstructor
            ? $"@{typeName.ToString()} New("
            : $"{returnType.GetCSharpExpression(true)} @{method.Name}(");

        var isStatic = method.AccessFlags.HasFlag(AccessFlags.Static);

        {
            var isFirst = true;
            if (!isStatic && !isConstructor)
            {
                sourceBuilder.Append(
                    $"this {typeFullName.ToString().ToGlobalTypeName()} @this");
                isFirst = false;
            }

            foreach (var argument in tempArguments)
            {
                if (!isFirst) sourceBuilder.Append(", ");
                sourceBuilder.Append(argument.CSharpExpression);
                sourceBuilder.Append(" ");
                sourceBuilder.Append(argument.Name);
                isFirst = false;
            }
        }

        sourceBuilder.Append(")");

        sourceBuilder.AppendLine();

        sourceBuilder.AppendLine("    {");

        if (isConstructor)
            sourceBuilder.AppendLine(
                $"        var @this = @{typeName.ToString()}.UnsafeFromRawObjectAndDeleteLocalRef(global::UnityEngine.AndroidJNI.AllocObject({classPointerNameStr})) ?? throw new global::System.InvalidOperationException();");

        sourceBuilder.AppendLine(
            $"        if ({methodPointerName} == (nint)0) {methodPointerName} = global::UnityEngine.AndroidJNI.Get{(isStatic ? "Static" : "")}MethodID({classPointerNameStr}, @\"{name}\", @\"{descriptor}\");");

        sourceBuilder.AppendLine(tempArguments.Count != 0
            ? $"        global::System.Span<global::UnityEngine.jvalue> __ABG__args = stackalloc UnityEngine.jvalue[{tempArguments.Count}];"
            : "        global::System.Span<global::UnityEngine.jvalue> __ABG__args = global::System.Span<global::UnityEngine.jvalue>.Empty;");

        var context = new MarshalingContext();
        var call = new StringBuilder();

        for (var i = 0; i < tempArguments.Count; i++)
        {
            var (type, paramName, _) = tempArguments[i];
            var initializer = type.JValueInitializer(context, paramName);
            call.AppendLine(
                $"            __ABG__args[{i}] = new global::UnityEngine.jvalue() {{ {initializer} }};");
        }

        // call
        {
            call.Append("            ");
            if (!returnType.IsVoid) call.Append("return ");

            call.Append(returnType.ToCSharpValue(
                $"global::UnityEngine.AndroidJNI.{returnType.CallMethodNameWithReturn(isStatic)}({(isStatic ? classPointerNameStr : "@this.GetRawObject()")}, {methodPointerName}, __ABG__args)"));
            call.AppendLine(";");
        }

        if (isConstructor)
            call.AppendLine("            return @this;");

        sourceBuilder.Append(context.PreCall);
        sourceBuilder.AppendLine("        try");
        sourceBuilder.AppendLine("        {");
        sourceBuilder.Append(call);
        sourceBuilder.AppendLine("        }");
        sourceBuilder.AppendLine("        finally");
        sourceBuilder.AppendLine("        {");
        sourceBuilder.AppendLine("            global::AndroidBindgen.AndroidJNIEx.CheckException();");
        sourceBuilder.Append(context.PostCall);
        sourceBuilder.AppendLine("        }");

        sourceBuilder.AppendLine("    }");
    }

    private static void AppendJavadoc(StringBuilder sourceBuilder, XmlCDataSection? javadoc)
    {
        if (javadoc == null || string.IsNullOrEmpty(javadoc.Data)) return;
        sourceBuilder.AppendLine(string.Join("\n", javadoc.Data.Split("\n").Select(line => $"/// {line}")));
    }
